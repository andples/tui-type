/// Unknown character: a hollow box.
const MISSING: Glyph = [0b111, 0b101, 0b101, 0b101, 0b111, 0b000];

fn parse(rows: &[&str; 6]) -> Glyph {
    let mut g = [0u8; 6];
    for (i, row) in rows.iter().enumerate() {
        for (j, c) in row.chars().take(3).enumerate() {
            if c == '#' {
                g[i] |= 1 << (2 - j);
            }
        }
    }
    g
}

fn table() -> &'static HashMap<char, Glyph> {
    static TABLE: OnceLock<HashMap<char, Glyph>> = OnceLock::new();
    TABLE.get_or_init(|| SOURCE.iter().map(|(c, rows)| (*c, parse(rows))).collect())
}

/// Look up a glyph, stripping common Latin accents to their base letter.
pub fn glyph(ch: char) -> Glyph {
    let t = table();
    if let Some(g) = t.get(&ch) {
        return *g;
    }
    let base = match ch {
        'à'..='å' => 'a',
        'è'..='ë' => 'e',
        'ì'..='ï' => 'i',
        'ò'..='ö' => 'o',
        'ù'..='ü' => 'u',
        'ç' => 'c',
        'ñ' => 'n',
        'ý' | 'ÿ' => 'y',
        'À'..='Å' => 'A',
        'È'..='Ë' => 'E',
        'Ì'..='Ï' => 'I',
        'Ò'..='Ö' => 'O',
        'Ù'..='Ü' => 'U',
        'Ç' => 'C',
        'Ñ' => 'N',
        _ => return MISSING,
    };
    t.get(&base).copied().unwrap_or(MISSING)
}

/// Pixel at (`x`, `y`) inside the 4×6 advance box; column 3 is the gap.
pub fn pixel(g: &Glyph, x: u16, y: u16) -> bool {
    if x >= 3 || y >= GLYPH_H {
        return false;
    }
    (g[y as usize] >> (2 - x)) & 1 == 1
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_source_row_is_three_wide() {
        for (c, rows) in SOURCE {
            for r in rows {
                assert_eq!(r.len(), 3, "glyph {c:?} row {r:?}");
                assert!(r.chars().all(|x| x == '#' || x == '.'), "glyph {c:?}");
            }
        }
    }

    #[test]
    fn no_duplicate_glyphs_among_letters() {
        let mut seen: HashMap<Glyph, char> = HashMap::new();
        for (c, rows) in SOURCE {
            if !c.is_ascii_alphanumeric() {
                continue;
            }
            if let Some(prev) = seen.insert(parse(rows), *c) {
                panic!("{c:?} and {prev:?} share a bitmap");
            }
        }
    }

    #[test]
    fn lookup_and_fallbacks() {
        assert_eq!(glyph('é'), glyph('e'));
        assert_eq!(glyph('☃'), MISSING);
        assert!(pixel(&glyph('l'), 1, 0));
        assert!(!pixel(&glyph('l'), 3, 0), "column 3 is always the gap");
    }
}
